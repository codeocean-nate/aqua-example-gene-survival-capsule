"""Generate the shared synthetic gene annotation used by several example capsules.

Deterministic (seed 7). Real HGNC symbols for the first 60 genes so users can ask
for familiar genes (TP53, EGFR...); IDs are synthetic (SYN######) and all other
fields are made up. Output: datasets/synthetic-gene-annotation/genes.tsv
"""
import os
import random

random.seed(7)
KNOWN = """TP53 EGFR KRAS BRCA1 BRCA2 MYC PIK3CA PTEN APC RB1 CDKN2A ERBB2 BRAF NRAS
ALK MET ATM CHEK2 IDH1 IDH2 VHL NF1 SMAD4 CTNNB1 NOTCH1 FGFR1 FGFR2 FGFR3 KIT PDGFRA
ESR1 AR GATA3 FOXA1 CDH1 ARID1A KMT2D STK11 KEAP1 MTOR TSC1 TSC2 MDM2 CCND1 CDK4 CDK6
BCL2 MCL1 JAK2 STAT3 VEGFA HIF1A EZH2 DNMT3A TET2 NPM1 FLT3 RUNX1 SF3B1 CD274""".split()
assert len(KNOWN) == 60
CHROMS = [str(i) for i in range(1, 23)] + ["X"]
out = os.path.join(os.path.dirname(__file__), "..", "synthetic-gene-annotation")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "genes.tsv"), "w") as f:
    f.write("gene_id\tsymbol\tbiotype\tchrom\tstart\tend\n")
    for i in range(1, 2001):
        sym = KNOWN[i - 1] if i <= 60 else f"SYNG{i:04d}"
        bt = "protein_coding" if i <= 60 or random.random() < 0.7 else "lncRNA"
        start = random.randint(10_000, 200_000_000)
        f.write(f"SYN{i:06d}\t{sym}\t{bt}\t{random.choice(CHROMS)}\t{start}\t{start + random.randint(1_000, 150_000)}\n")
with open(os.path.join(out, "DATASET.md"), "w") as f:
    f.write("""# synthetic-gene-annotation

**Synthetic data — not real annotation.** Generated by `_generators/synthetic-gene-annotation.py` (seed 7).

`genes.tsv` — 2,000 genes, tab-separated, one row per gene:

| column | meaning |
|---|---|
| gene_id | synthetic stable ID, `SYN000001`..`SYN002000` (primary key used by other datasets) |
| symbol | real HGNC symbol for SYN000001–SYN000060 (TP53, EGFR, KRAS, …); `SYNG####` otherwise |
| biotype | `protein_coding` or `lncRNA` |
| chrom, start, end | made-up coordinates |

Mount as `/data/synthetic-gene-annotation`. Shared by the bulk RNA-seq and gene-survival capsules.
""")
print("ok")
